import { randomUUID } from "node:crypto";
import { readFileSync } from "node:fs";
import { Client } from "pg";
import assert from "node:assert/strict";
import test from "node:test";

// This opt-in fixture uses an explicitly configured local test database only.
const databaseUrl = process.env.ACCOUNT_TEST_DATABASE_URL;
test(
  "preserves credentials, OAuth identities and sessions during migration",
  { skip: !databaseUrl },
  async () => {
    const url = new URL(databaseUrl!);
    if (!["localhost", "127.0.0.1", "::1", "[::1]"].includes(url.hostname))
      throw new Error("Requires a local test database");
    const client = new Client({ connectionString: url.toString() });
    const schema = `account_migration_${randomUUID().replaceAll("-", "")}`;
    await client.connect();
    try {
      await client.query(`CREATE SCHEMA "${schema}"`);
      await client.query(`SET search_path TO "${schema}", public`);
      await client.query(`
      CREATE TYPE "PlatformRole" AS ENUM ('SUPER_ADMIN', 'USER');
      CREATE TABLE "User" (id text PRIMARY KEY, password text, "createdAt" timestamp DEFAULT now(), role "PlatformRole" DEFAULT 'USER');
      CREATE TABLE "SocialAccount" (
        id text DEFAULT encode(gen_random_bytes(24), 'hex'), "userId" text NOT NULL,
        provider text NOT NULL, "providerUserId" text NOT NULL, "createdAt" timestamp DEFAULT now(),
        CONSTRAINT "SocialAccount_pkey" PRIMARY KEY (id),
        CONSTRAINT "SocialAccount_userId_fkey" FOREIGN KEY ("userId") REFERENCES "User"(id)
      );
      CREATE UNIQUE INDEX "SocialAccount_provider_providerUserId_key" ON "SocialAccount"(provider, "providerUserId");
      CREATE TABLE "RefreshToken" (id text PRIMARY KEY, "userId" text REFERENCES "User"(id), "tokenHash" text);
      INSERT INTO "User" (id, password) VALUES ('password-user', 'unchanged-hash'), ('oauth-user', NULL), ('mixed-user', 'mixed-hash');
      INSERT INTO "SocialAccount" (id, "userId", provider, "providerUserId") VALUES ('google-link', 'oauth-user', 'google', 'google-sub'), ('apple-link', 'mixed-user', 'apple', 'apple-sub');
      INSERT INTO "RefreshToken" VALUES ('session', 'mixed-user', 'existing-session-hash');
    `);
      await client.query(
        readFileSync(
          new URL(
            "../prisma/migrations/20261018180000_unify_accounts_and_platform_roles/migration.sql",
            import.meta.url,
          ),
          "utf8",
        ),
      );
      const accounts = (
        await client.query(
          'SELECT id, "userId", provider, "providerUserId", "passwordHash" FROM "Account" ORDER BY "userId", provider',
        )
      ).rows;
      assert.equal(accounts.length, 4);
      assert.ok(
        accounts.some((account) =>
          Object.entries({
            id: "google-link",
            userId: "oauth-user",
            provider: "google",
            providerUserId: "google-sub",
            passwordHash: null,
          }).every(([key, value]) => account[key] === value),
        ),
      );
      assert.ok(
        accounts.some((account) =>
          Object.entries({
            userId: "password-user",
            provider: "credentials",
            providerUserId: "password-user",
            passwordHash: "unchanged-hash",
          }).every(([key, value]) => account[key] === value),
        ),
      );
      assert.ok(
        accounts.some((account) =>
          Object.entries({
            userId: "mixed-user",
            provider: "credentials",
            passwordHash: "mixed-hash",
          }).every(([key, value]) => account[key] === value),
        ),
      );
      assert.deepEqual((await client.query('SELECT * FROM "RefreshToken"')).rows, [
        { id: "session", userId: "mixed-user", tokenHash: "existing-session-hash" },
      ]);
      await client.query(`UPDATE "User" SET role = 'CONTENT_ADMIN' WHERE id = 'oauth-user'`);
      await assert.rejects(
        client.query(
          `INSERT INTO "Account" ("userId", provider, "providerUserId", "passwordHash") VALUES ('password-user', 'credentials', 'another-id', 'hash')`,
        ),
      );
    } finally {
      await client.query("ROLLBACK");
      await client.query("SET search_path TO public");
      // The name is generated by this test; no application tables are removed.
      await client.query(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`);
      await client.end();
    }
  },
);
